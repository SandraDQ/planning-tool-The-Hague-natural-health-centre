// Saves the original logo files and favicon from the homepage, and writes brand/notes.md with fonts and colours.
import { BASE, chromium, get, save, openPage, originalImage } from "./web.mjs";

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await openPage(page, BASE + "/");

const info = await page.evaluate(() => {
  const hex = (c) => {
    const m = c.match(/rgba?\(([\d.]+),\s*([\d.]+),\s*([\d.]+)(?:,\s*([\d.]+))?\)/);
    if (!m || m[4] === "0") return null;
    return "#" + m.slice(1, 4).map((x) => (+x).toString(16).padStart(2, "0")).join("") + (m[4] && m[4] !== "1" ? ` (alpha ${m[4]})` : "");
  };
  const count = (map, k, n = 1) => k && map.set(k, (map.get(k) ?? 0) + n);
  const text = new Map(), bg = new Map(), fonts = new Map();
  for (const el of document.querySelectorAll("#SITE_CONTAINER *")) {
    const s = getComputedStyle(el), r = el.getBoundingClientRect();
    if (s.display === "none" || s.visibility === "hidden" || !r.width || !r.height) continue;
    const own = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent.trim());
    if (own) { count(text, hex(s.color)); count(fonts, s.fontFamily); }
    if (r.width * r.height > 2000) count(bg, hex(s.backgroundColor), Math.round((r.width * r.height) / 10000) || 1);
  }
  // Wix theme variables (--color_N as "r,g,b", --font_N as CSS font shorthand), read from computed style.
  const vars = {};
  const cs = getComputedStyle(document.querySelector("#SITE_CONTAINER") ?? document.body);
  for (const [kind, max] of [["color", 80], ["font", 20]]) {
    for (let i = 0; i <= max; i++) {
      const v = cs.getPropertyValue(`--${kind}_${i}`).trim();
      if (v) vars[`--${kind}_${i}`] = kind === "color" ? `${v} = ${hex(`rgb(${v})`)}` : v;
    }
  }
  const sample = (sel) => [...document.querySelectorAll(sel)].filter((e) => e.innerText?.trim()).slice(0, 2).map((e) => {
    const s = getComputedStyle(e);
    return { sel, text: e.innerText.trim().slice(0, 40), font: s.fontFamily, size: s.fontSize, weight: s.fontWeight, color: hex(s.color), bg: hex(s.backgroundColor) };
  });
  const logo = document.querySelector("#SITE_HEADER img");
  const footerLogo = document.querySelector("#SITE_FOOTER img");
  return {
    logo: { src: logo?.src, alt: logo?.alt }, footerLogo: { src: footerLogo?.src, alt: footerLogo?.alt },
    icons: [...document.querySelectorAll('link[rel*="icon"]')].map((l) => ({ rel: l.rel, href: l.href, sizes: String(l.sizes) })),
    textColours: [...text].sort((a, b) => b[1] - a[1]), backgrounds: [...bg].sort((a, b) => b[1] - a[1]),
    fonts: [...fonts].sort((a, b) => b[1] - a[1]),
    loadedFonts: [...new Set([...document.fonts].filter((f) => f.status === "loaded").map((f) => `${f.family} ${f.weight} ${f.style}`))],
    vars,
    samples: ["h1", "h2", "h3", "p", "#SITE_HEADER nav a", "a[data-testid=linkElement] span", "#SITE_FOOTER p"].flatMap(sample),
  };
});
await browser.close();

async function download(url, name) {
  const res = await get(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const ext = (res.headers.get("content-type") ?? "").split("/")[1]?.replace("jpeg", "jpg").replace(/[^a-z]/g, "") || "bin";
  const file = `${name}.${ext}`;
  save(`brand/${file}`, Buffer.from(await res.arrayBuffer()));
  return file;
}

const files = [];
const logoOrig = originalImage(info.logo.src);
files.push(["Header logo, original upload (no Wix transform)", logoOrig, await download(logoOrig, "logo-header-original")]);
// The header shows a Wix crop of that upload; keep the crop at native resolution (crop only, no resize).
const crop = decodeURIComponent(info.logo.src).match(/\/v1\/crop\/([^/]+)\//)?.[1];
if (crop) {
  const url = `${logoOrig}/v1/crop/${crop}/${logoOrig.split("/").pop()}`;
  files.push([`Header logo as cropped on the site (crop ${crop}, no resize)`, url, await download(url, "logo-header-cropped-as-shown")]);
}
if (info.footerLogo.src) {
  const u = originalImage(info.footerLogo.src);
  files.push(["Footer logo, original upload", u, await download(u, "logo-footer-original")]);
}
const icon = info.icons[0]?.href;
if (icon) {
  files.push(["Favicon as served (192x192)", icon, await download(icon, "favicon-192")]);
  files.push(["Favicon, original upload", originalImage(icon), await download(originalImage(icon), "favicon-original")]);
}
files.push(["/favicon.ico as served by Wix", `${BASE}/favicon.ico`, await download(`${BASE}/favicon.ico`, "favicon-ico")]);

const top = (list, n) => list.slice(0, n).map(([k, c]) => `| \`${k}\` | ${c} |`).join("\n");
save("brand/computed-styles.json", JSON.stringify(info, null, 1) + "\n");
save("brand/notes.md", `# Brand notes (from ${BASE}/, rendered at 1440px)

Generated by \`scripts/wix-export/brand.mjs\`. Raw data in \`computed-styles.json\`.

## Files

| File | What | Source |
|---|---|---|
${files.map(([what, url, f]) => `| \`${f}\` | ${what} | ${url} |`).join("\n")}

Header logo alt text: "${info.logo.alt}". Footer logo alt text: "${info.footerLogo.alt}".

## Fonts

Font stacks used by visible text (count = elements with own text):

| font-family | count |
|---|---|
${top(info.fonts, 12)}

Web fonts loaded: ${info.loadedFonts.map((f) => `\`${f}\``).join(", ") || "(none reported)"}

## Colours

Text colours (count = elements):

| colour | count |
|---|---|
${top(info.textColours, 12)}

Background colours (weighted by area, in 10,000 px² units):

| colour | weight |
|---|---|
${top(info.backgrounds, 12)}

## Wix theme variables

${Object.entries(info.vars).map(([k, v]) => `- \`${k}\`: \`${v}\``).join("\n") || "(none found)"}

(Wix \`--color_N\` values are "r,g,b" triplets.)

## Samples

| selector | text | font | size | weight | colour | background |
|---|---|---|---|---|---|---|
${info.samples.map((s) => `| \`${s.sel}\` | ${s.text.replace(/\|/g, "/").replace(/\n/g, " ")} | ${s.font} | ${s.size} | ${s.weight} | ${s.color} | ${s.bg ?? ""} |`).join("\n")}
`);
